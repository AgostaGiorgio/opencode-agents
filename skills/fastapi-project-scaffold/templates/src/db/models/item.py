from datetime import datetime
from typing import Optional
from uuid import UUID

from pydantic import BaseModel, Field


class Item(BaseModel):
    id: UUID = Field(..., description="Unique identifier (generated by the database)")
    name: str = Field(..., description="Item name")
    description: Optional[str] = Field(None, description="Optional item description")
    created_at: datetime = Field(..., description="Creation timestamp")


class ItemCreate(BaseModel):
    name: str = Field(..., description="Item name")
    description: Optional[str] = Field(None, description="Optional item description")

    def to_dict(self) -> dict:
        """Insert/update parameters, adapted to what the driver expects."""
        return {"name": self.name, "description": self.description}
